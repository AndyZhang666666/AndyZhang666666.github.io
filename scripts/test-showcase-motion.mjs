import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.SHOWCASE_BASE_URL||'http://127.0.0.1:8811',out='.taste-skill/new-work-20261029/material';
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const checks=[],errors=[];
try{
 const p=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
 p.on('pageerror',error=>errors.push(error.message));
 await p.goto(base+'/#selected',{waitUntil:'networkidle'});
 await p.locator('.showcase-material-ready').waitFor();
 const style=await p.locator('.showcase-stage').evaluate(el=>{const s=getComputedStyle(el);return{blur:s.backdropFilter||s.webkitBackdropFilter,background:s.backgroundColor};});
 assert.match(style.blur,/blur/);assert.ok(style.background.startsWith('rgba'));
 assert.deepEqual(await p.locator('main>section[id]').evaluateAll(nodes=>nodes.slice(0,3).map(n=>n.id)),['top','about','selected']);
 assert.equal(await p.locator('.section-num,[data-num],.ai-view-num,.principle-num').count(),0);
 checks.push('Translucent blurred material; selected work follows About; decorative indexes removed');
 await p.locator('[data-selected-id=taste]').click();
 await p.waitForFunction(()=>parseFloat(document.querySelector('.showcase-choices').style.getPropertyValue('--pick-y'))>80);
 assert.equal(await p.locator('.showcase-panel:not([hidden])').getAttribute('data-preview'),'taste');
 for(const id of ['trust','execution','bundles'])await p.locator(`[data-selected-id="${id}"]`).click();
 assert.equal(await p.locator('.showcase-panel:not([hidden])').count(),1);
 assert.equal(await p.locator('.showcase-panel:not([hidden])').getAttribute('data-preview'),'bundles');
 await p.locator('[data-bundle-adoption="0.5"]:not(:disabled)').waitFor();
 checks.push('Shared glass marker moves between selections; rapid switching retains exactly one correct panel');
 const stage=p.locator('.showcase-stage');
 await stage.hover({position:{x:80,y:100}});
 await p.waitForFunction(()=>Math.abs(parseFloat(document.querySelector('.showcase-stage').style.getPropertyValue('--material-rotate-y')))>0.1);
 const shiftBefore=await p.locator('#selected').evaluate(el=>el.style.getPropertyValue('--material-stage-y'));
 await p.evaluate(()=>window.scrollBy(0,150));
 await p.waitForFunction(before=>document.querySelector('#selected').style.getPropertyValue('--material-stage-y')!==before,shiftBefore);
 checks.push('Pointer depth and bounded scroll offset respond to real input');
 const button=p.locator('[data-bundle-adoption="0.5"]');await button.hover();await p.mouse.down();
 const compressed=await button.evaluate(el=>el.getAnimations().some(animation=>animation.effect.getKeyframes().some(frame=>frame.scale&&parseFloat(frame.scale)<1)));
 await p.mouse.up();assert.ok(compressed);
 await p.locator('#selected').evaluate(el=>Promise.all(el.getAnimations({subtree:true}).map(animation=>animation.finished.catch(()=>{}))));
 await p.locator('#selected').screenshot({path:out+'/glass-desktop.png'});
 checks.push('Pointer press creates short physical compression and release');
 await p.emulateMedia({reducedMotion:'reduce'});
 await p.waitForFunction(()=>getComputedStyle(document.querySelector('.showcase-stage')).transform==='none');
 await p.locator('[data-selected-id=trust]').click();await p.locator('[data-eval-locate]:not(:disabled)').waitFor();await p.locator('[data-eval-locate]').click();
 assert.equal(await p.locator('[data-eval-source-quote] mark').count(),1);
 assert.equal(await p.locator('#selected').evaluate(el=>el.getAnimations({subtree:true}).length),0);
 checks.push('Reduced motion stops spatial animation while keeping evidence feedback usable');
 const touch=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'no-preference'}),mobile=await touch.newPage();
 mobile.on('pageerror',error=>errors.push(error.message));
 await mobile.goto(base+'/#selected',{waitUntil:'networkidle'});await mobile.locator('[data-selected-id=execution]').tap();
 await mobile.locator('[data-agent-check]:not(:disabled)').waitFor();await mobile.locator('[data-agent-check]').tap();assert.equal(await mobile.locator('[data-agent-result]').isVisible(),true);
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
 await mobile.locator('#selected').evaluate(el=>Promise.all(el.getAnimations({subtree:true}).map(animation=>animation.finished.catch(()=>{}))));
 await mobile.locator('#selected').screenshot({path:out+'/glass-touch.png'});await touch.close();
 checks.push('Touch selection and execution-record preview work at 390px without horizontal overflow');
 assert.deepEqual(errors,[]);
 await fs.writeFile(out+'/report.json',JSON.stringify({passed:true,at:new Date().toISOString(),checks,errors},null,2));
 console.log('PASS: '+checks.length+' material/motion checks, desktop pointer, touch and reduced motion.');
}finally{await browser.close()}
