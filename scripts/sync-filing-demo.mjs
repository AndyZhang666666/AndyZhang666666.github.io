// Build-artifact sync only. Pass the approved public filing-eval checkout as argument.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const source=path.resolve(process.argv[2]||'');
if(!process.argv[2]||!fs.existsSync(path.join(source,'demo','data.json')))throw new Error('Pass a built public filing-eval checkout');
const target=new URL('../demos/filing-eval/',import.meta.url);
fs.mkdirSync(target,{recursive:true});
for(const name of ['index.html','app.js','review-core.js','style.css','data.json','geist-regular.ttf','geist-medium.ttf','FONT-LICENSE.txt'])
  fs.copyFileSync(path.join(source,'demo',name),new URL(name,target));
const sha=execFileSync('git',['-C',source,'rev-parse','HEAD'],{encoding:'utf8'}).trim();
fs.writeFileSync(new URL('SOURCE.md',target),`# Generated demo assets\n\nSource: https://github.com/AndyZhang666666/filing-eval\nCommit: ${sha}\nGenerated by scripts/build-demo.mjs; copied by scripts/sync-filing-demo.mjs.\nAll announcement fixtures are synthetic. Runtime review notes remain local.\n`);
console.log('Synced public static demo and font license; no credentials or model requests.');
