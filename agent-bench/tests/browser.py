"""Real headless Chrome acceptance. No model calls; local mode writes synthetic SQLite data."""
import argparse
import json
from pathlib import Path
import re
from playwright.sync_api import sync_playwright, expect

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--base',default='http://127.0.0.1:8878/agent-bench/')
    p.add_argument('--out',default='agent-bench/test-artifacts')
    p.add_argument('--local',action='store_true')
    p.add_argument('--home',help='Optional full portfolio URL to verify the entry')
    args=p.parse_args();out=Path(args.out);out.mkdir(parents=True,exist_ok=True)
    checks=[];errors=[]
    def passed(name):checks.append(name);print('PASS',name,flush=True)
    with sync_playwright() as pw:
        browser=pw.chromium.launch(channel='chrome',headless=True)
        context=browser.new_context(viewport={'width':1440,'height':1000},reduced_motion='reduce',accept_downloads=True)
        page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(args.base);page.wait_for_load_state('networkidle')
        expect(page.locator('#case-select option')).to_have_count(10)
        expect(page.locator('#source-label')).to_contain_text('不调用 AI')
        page.screenshot(path=str(out/'desktop-ready.png'),full_page=True)
        passed('ten original cases and explicit example source')
        cases=page.locator('#case-select option').evaluate_all('(options)=>options.map(o=>o.value)')
        for cid in cases:
            page.select_option('#case-select',cid)
            page.locator('#watch').focus();page.keyboard.press('Enter')
            expect(page.locator('#play-status')).to_contain_text('播放结束')
            expect(page.locator('.result')).to_have_count(2)
            expect(page.locator('#verdict')).to_be_visible()
            assert not page.evaluate('document.documentElement.scrollWidth>innerWidth')
            if cid=='normal':expect(page.locator('.result .state.good')).to_have_count(2)
            if cid=='timeout':expect(page.locator('[data-policy=baseline] .state')).to_have_text('结果未知')
        passed('all ten public example flows and keyboard run')
        page.select_option('#case-select','timeout');page.locator('#watch').click();expect(page.locator('#play-status')).to_contain_text('播放结束')
        page.screenshot(path=str(out/'desktop.png'),full_page=True)
        summaries=page.locator('.result details summary')
        summaries.first.focus();page.keyboard.press('Enter')
        expect(page.locator('.checks').first).to_be_visible()
        page.locator('[data-policy=hardened] details').nth(1).locator('summary').click()
        expect(page.locator('.raw').last).to_contain_text('operation_status')
        passed('native disclosure keyboard and original operation evidence')
        with page.expect_download() as info:page.locator('.export').first.click()
        download=info.value;file=out/'export-example.json';download.save_as(file)
        record=json.loads(file.read_text());assert record['source']=='example';assert len(record['ticket']['notes'])==1
        post_count=[];page.on('request',lambda req:post_count.append(req.url) if req.method=='POST' else None)
        page.get_by_text('导入一次运行，进行只读回放',exact=True).click();before=len(post_count)
        page.locator('#import-record').set_input_files(str(file));expect(page.locator('#import-status')).to_contain_text('完成只读回放')
        assert len(post_count)==before;expect(page.locator('#source-label')).to_contain_text('不调用 AI')
        passed('export and read-only import produce no mutation requests')
        bad=out/'invalid.json';bad.write_text('{"schema":"not-an-agent-bench-record"}')
        page.locator('#import-record').set_input_files(str(bad));expect(page.locator('#error')).to_contain_text('无法回放')
        passed('invalid import is recoverable')
        for width in (390,768,1280):
            page.set_viewport_size({'width':width,'height':900})
            page.select_option('#case-select','timeout');page.locator('#watch').click();expect(page.locator('#play-status')).to_contain_text('播放结束')
            for summary in page.locator('.technical[open] > summary').all():summary.click()
            assert not page.evaluate('document.documentElement.scrollWidth>innerWidth')
            if width==390:page.screenshot(path=str(out/'mobile.png'),full_page=True)
        passed('390, 768 and 1280px retain both comparison results without overflow')
        page.set_viewport_size({'width':1440,'height':1000});page.emulate_media(reduced_motion='no-preference')
        page.select_option('#case-select','normal');page.locator('#watch').click();page.locator('#pause').click()
        expect(page.locator('#pause')).to_have_text('继续播放');page.locator('#pause').click()
        expect(page.locator('#play-status')).to_contain_text('播放结束',timeout=15000);page.emulate_media(reduced_motion='reduce')
        passed('pause and continue example playback')
        if args.local:
            tech=page.get_by_text('技术详情与运行边界',exact=True)
            if page.locator('.technical').first.evaluate('(d)=>!d.open'):tech.click()
            expect(page.locator('#run-model')).to_be_disabled()
            def start(cid):
                if page.locator('.technical').first.evaluate('(d)=>!d.open'):tech.click()
                page.select_option('#case-select',cid);page.locator('#run-program').click()
                expect(page.locator('.approval')).to_have_count(2)
                expect(page.locator('.result-summary').first).to_contain_text('尚未写入')
                expect(page.locator('.checks')).to_have_count(0)
            def confirm(policy):
                column=page.locator('[data-policy='+policy+']')
                column.get_by_role('button',name='确认此变更',exact=True).click()
                expect(page.locator('#run-program')).to_be_enabled(timeout=15000)
            def records():
                ids=page.evaluate('JSON.parse(localStorage.getItem("agent-bench-runs-v1"))')
                return [page.request.get(args.base.split('/agent-bench')[0]+'/api/runs/'+rid).json() for rid in ids]
            start('normal');tech.click();page.screenshot(path=str(out/'desktop-approval.png'),full_page=True)
            confirm('baseline');confirm('hardened')
            assert all(r['evaluation']['passed'] for r in records())
            passed('local normal flow: exact approval, SQLite writes and checks')
            start('timeout');confirm('baseline');confirm('hardened')
            expect(page.locator('[data-policy=baseline] .state')).to_have_text('结果未知')
            page.locator('[data-policy=baseline]').get_by_role('button',name='查询原操作并恢复').click()
            expect(page.locator('#run-program')).to_be_enabled()
            assert all(len(r['operations'])==1 and len(r['ticket']['notes'])==1 for r in records())
            passed('timeout recovery queries original operation and adds no duplicate note')
            start('duplicate');confirm('baseline');confirm('hardened')
            assert all(any(e['result'].get('deduplicated') for e in r['events']) for r in records())
            passed('duplicate transport delivery returns original receipt')
            start('conflict');confirm('baseline');confirm('hardened')
            expect(page.locator('[data-policy=hardened] .approval')).to_contain_text('v2')
            confirm('hardened');a,b=records();assert not a['ticket']['notes'] and len(b['ticket']['notes'])==1
            passed('stale approval is rejected and hardened flow asks again for v2')
            start('cancel')
            for policy in ('baseline','hardened'):
                page.locator('[data-policy='+policy+']').get_by_role('button',name='取消后续步骤').click();expect(page.locator('#run-program')).to_be_enabled()
            assert all(r['run']['state']=='cancelled' and r['ticket']['notes']==[] for r in records())
            passed('cancel before write leaves both databases unchanged')
            start('interrupted');confirm('baseline');confirm('hardened')
            assert all(r['run']['state']=='unknown' for r in records())
            page.reload();page.wait_for_load_state('networkidle');page.get_by_text('技术详情与运行边界',exact=True).click();page.locator('#restore').click()
            expect(page.locator('#run-program')).to_be_enabled()
            for policy in ('baseline','hardened'):
                page.locator('[data-policy='+policy+']').get_by_role('button',name='查询原操作并恢复').click();expect(page.locator('#run-program')).to_be_enabled()
            assert all(r['evaluation']['passed'] and len(r['operations'])==1 for r in records())
            passed('refresh resumes persistent run IDs and safely recovers interrupted commits')
            page.set_viewport_size({'width':390,'height':844});start('normal')
            tech.click();page.screenshot(path=str(out/'mobile-approval.png'),full_page=True);confirm('baseline');confirm('hardened')
            assert not page.evaluate('document.documentElement.scrollWidth>innerWidth')
            passed('mobile local approval flow completes both policies')
            page.set_viewport_size({'width':1440,'height':1000})
            tech.click()
            page.route('**/api/runs/*/step',lambda route:route.fulfill(status=503,content_type='application/json',body='{"message":"测试接口中断，请恢复原运行"}'))
            page.select_option('#case-select','normal');page.locator('#run-program').click();expect(page.locator('#error')).to_contain_text('测试接口中断')
            expect(page.locator('#source-label')).to_contain_text('本地程序测试');page.unroute('**/api/runs/*/step')
            page.locator('#restore').click();expect(page.locator('.approval')).to_have_count(2)
            passed('API failure preserves run and never silently converts to example mode')
        if args.home:
            home=context.new_page();home.goto(args.home);home.wait_for_load_state('networkidle')
            entry=home.locator('#project-agent-bench');expect(entry).to_be_visible();expect(entry.locator('a[href="/agent-bench/"]')).to_have_count(1)
            passed('portfolio entry preserved and routes to agent-bench')
        assert not errors,errors
        passed('no browser JavaScript errors')
        browser.close()
    (out/'browser-results.json').write_text(json.dumps({'base':args.base,'local':args.local,'checks':checks,'passed':len(checks),'errors':errors,'model_calls':0},ensure_ascii=False,indent=2)+'\n')
    print('Browser checks:',len(checks))

if __name__=='__main__':main()
