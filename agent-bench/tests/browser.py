"""Guided read-only replay and preserved local sandbox acceptance. No real model calls."""
import argparse
import json
from pathlib import Path
import re
from playwright.sync_api import sync_playwright, expect

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--base',default='http://127.0.0.1:8893/agent-bench/')
    p.add_argument('--out',default='agent-bench/test-artifacts')
    p.add_argument('--local',action='store_true')
    p.add_argument('--home',help='Optional full portfolio URL to verify the entry')
    args=p.parse_args();out=Path(args.out);out.mkdir(parents=True,exist_ok=True)
    checks=[];errors=[];writes=[]
    fixture=json.loads((Path(__file__).resolve().parents[1]/'samples/examples.json').read_text())
    def passed(name):checks.append(name);print('PASS',name,flush=True)
    with sync_playwright() as pw:
        browser=pw.chromium.launch(channel='chrome',headless=True)
        context=browser.new_context(viewport={'width':1440,'height':1000},reduced_motion='reduce',accept_downloads=True)
        page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
        page.on('request',lambda r:writes.append(r.url) if r.method not in ('GET','HEAD') else None)
        page.goto(args.base);page.wait_for_load_state('networkidle')
        expect(page.locator('#case-select option')).to_have_count(10)
        expect(page.locator('[data-case]')).to_have_count(3)
        expect(page.locator('#source-label')).to_contain_text('不调用 AI')
        expect(page.locator('#condition')).not_to_contain_text('数据库已提交')
        expect(page.locator('#watch')).to_have_text('开始逐步回放')
        expect(page.locator('#verdict')).to_be_hidden()
        page.screenshot(path=str(out/'desktop-ready.png'),full_page=True)
        passed('three featured cases, ten original cases, initial state without final-state spoiler')
        page.locator('#watch').focus();page.keyboard.press('Enter')
        expect(page.locator('#play-status')).to_contain_text('关键节点',timeout=12000)
        expect(page.locator('#step-label')).to_have_text('5 / 8 项事件')
        expect(page.locator('#checkpoint')).to_contain_text('可以直接重试吗')
        expect(page.locator('#verdict')).to_be_hidden()
        for policy in ('baseline','hardened'):
            card=page.locator('.result[data-policy='+policy+']')
            expect(card.locator('.ticket-data dd').nth(2)).to_have_text('0 条')
            expect(card.locator('.state-basis')).to_contain_text('不能当作当前数据库结果')
        page.screenshot(path=str(out/'desktop-checkpoint.png'),full_page=True)
        passed('automatic checkpoint at lost receipt, no premature database or grade reveal')
        page.locator('#next').click()
        expect(page.locator('.result[data-policy=hardened] .ticket-data dd').nth(2)).to_have_text('1 条')
        expect(page.locator('.result[data-policy=baseline] .ticket-data dd').nth(2)).to_have_text('0 条')
        expect(page.locator('.result[data-policy=hardened] .state-basis')).to_contain_text('事件 6')
        page.locator('#previous').click()
        expect(page.locator('.result[data-policy=hardened] .ticket-data dd').nth(2)).to_have_text('0 条')
        expect(page.locator('#verdict')).to_be_hidden()
        passed('next follows original-operation receipt; previous removes future knowledge')
        page.locator('#watch').click();expect(page.locator('#watch')).to_have_text('暂停播放')
        page.locator('#watch').click();expect(page.locator('#watch')).to_have_text('继续播放')
        paused=page.locator('#step-label').inner_text();page.wait_for_timeout(950)
        assert page.locator('#step-label').inner_text()==paused
        passed('manual pause interrupts autoplay without advancing another event')
        cases=page.locator('#case-select option').evaluate_all('(options)=>options.map(o=>o.value)')
        for cid in cases:
            page.select_option('#case-select',cid);page.locator('#finish').click()
            expect(page.locator('#play-status')).to_contain_text('播放结束')
            expect(page.locator('.result')).to_have_count(2)
            expect(page.locator('#verdict')).to_be_visible()
            for r in fixture['pairs'][cid]:
                card=page.locator('.result[data-policy='+r['run']['policy']+']')
                expect(card.locator('.ticket-data dd').nth(0)).to_have_text(r['ticket']['group'])
                expect(card.locator('.ticket-data dd').nth(2)).to_have_text(str(len(r['ticket']['notes']))+' 条')
                expect(card.locator('.case-result')).to_contain_text('符合案例预期' if r['evaluation']['passed'] else '未符合案例预期')
                assert ('good' if r['evaluation']['passed'] else 'bad') in card.locator('.case-result').get_attribute('class').split()
                assert card.locator('.event-node').count()==len(r['events'])
            if cid=='permission':
                expect(page.locator('.result .case-result.good')).to_have_count(2)
                expect(page.locator('#verdict')).to_contain_text('正确拒绝')
            assert not page.evaluate('document.documentElement.scrollWidth>innerWidth')
        passed('all ten final tickets and grades match archived records, including safe refusal and deduplication')
        page.select_option('#case-select','timeout');page.locator('#finish').click()
        expect(page.locator('.result[data-policy=baseline] .state.warning')).to_have_text('结果未知')
        expect(page.locator('.result[data-policy=baseline] .ticket-data dd').nth(2)).to_have_text('1 条')
        expect(page.locator('.result[data-policy=baseline] .state-basis')).to_contain_text('此后结果未核实')
        expect(page.locator('#verdict')).to_contain_text('不是模型成功率')
        page.screenshot(path=str(out/'desktop-final.png'),full_page=True)
        page.locator('[data-focus="hardened-5"]').click()
        expect(page.locator('#event-description')).to_contain_text('查到原操作已提交')
        page.locator('#event-raw summary').focus();page.keyboard.press('Enter')
        expect(page.locator('#event-json')).to_contain_text('operation_status')
        expect(page.locator('#event-facts')).to_contain_text('原操作标识')
        passed('final-state audit stays distinct from Agent knowledge; selectable event has inspectable evidence')
        with page.expect_download() as info:page.locator('.recap-card .export').first.click()
        file=out/'export-example.json';info.value.save_as(file)
        record=json.loads(file.read_text());assert record==fixture['pairs']['timeout'][0]
        with page.expect_download() as info:page.get_by_role('button',name='下载复盘 Markdown').click()
        md=out/'recap.md';info.value.save_as(md)
        assert record['run']['id'] in md.read_text()
        assert '不调用 AI' in md.read_text() and '未通过' in md.read_text()
        passed('original JSON export is unchanged; readable Markdown contains source, record IDs, effects and checks')
        page.get_by_text('导入一次运行，进行只读回放',exact=True).click()
        page.locator('#import-record').set_input_files(str(file))
        expect(page.locator('#import-status')).to_contain_text('逐步只读回放')
        expect(page.locator('.result')).to_have_count(1)
        expect(page.locator('#verdict')).to_be_hidden()
        page.locator('#finish').click();expect(page.locator('#verdict')).to_be_visible()
        expect(page.locator('#verdict')).not_to_contain_text('两条记录的最终数据库都已更新')
        for mode,source,label in [('program','program-test','程序记录回放'),('model','model-run','真实记录回放')]:
            imported=json.loads(json.dumps(record));imported['source']=source;imported['run']['mode']=mode
            f=out/(mode+'-import.json');f.write_text(json.dumps(imported))
            page.locator('#import-record').set_input_files(str(f));expect(page.locator('#source-label')).to_contain_text(label)
            expect(page.locator('#source-help')).to_contain_text('文件声明' if mode=='model' else '不计入模型评测')
        bad=out/'invalid.json';bad.write_text('{"schema":"not-an-agent-bench-record"}')
        page.locator('#import-record').set_input_files(str(bad));expect(page.locator('#error')).to_contain_text('无法回放')
        large=out/'large.json';large.write_text(' '*1048577)
        page.locator('#import-record').set_input_files(str(large));expect(page.locator('#error')).to_contain_text('1 MB')
        passed('read-only import retains provenance, rejects invalid/oversized files, and never invents paired outcomes')
        page.select_option('#case-select','timeout')
        for width in (390,768,1280):
            page.set_viewport_size({'width':width,'height':844 if width==390 else 1000})
            page.select_option('#case-select','timeout');page.locator('#finish').click()
            assert not page.evaluate('document.documentElement.scrollWidth>innerWidth')
            page.screenshot(path=str(out/('mobile-final.png' if width==390 else str(width)+'-final.png')),full_page=True)
            if width==390:
                expect(page.locator('.result:visible')).to_have_count(1)
                position=page.locator('#step-label').inner_text()
                page.locator('#tab-baseline').click();expect(page.locator('.result[data-policy=baseline]')).to_be_visible()
                assert page.locator('#step-label').inner_text()==position
                expect(page.locator('#event-position')).to_contain_text('基础策略')
                page.keyboard.press('ArrowRight');expect(page.locator('#tab-hardened')).to_be_focused()
                assert page.locator('#step-label').inner_text()==position
                page.screenshot(path=str(out/'mobile-viewport.png'))
                page.locator('#previous').focus();page.keyboard.press('Enter')
                expect(page.locator('#verdict')).to_be_hidden()
                assert page.locator('#progress').get_attribute('value')=='7'
                assert page.locator('.event-node').first.evaluate('(e)=>getComputedStyle(e).animationName')=='none'
        passed('390, 768 and 1280px; mobile policies share cursor, arrow keys work, reduced-motion skips animation only')
        assert not writes,writes
        passed('public playback, seek, event inspection, import and exports issue zero mutation requests')
        page.set_viewport_size({'width':1440,'height':1000})
        error_page=context.new_page();error_page.on('pageerror',lambda e:errors.append(str(e)))
        error_page.route('**/samples/examples.json',lambda route:route.fulfill(status=503,body='unavailable'))
        error_page.goto(args.base);expect(error_page.locator('#error')).to_contain_text('读取案例失败')
        expect(error_page.locator('#watch')).to_be_disabled()
        error_page.unroute('**/samples/examples.json');error_page.locator('#retry-load').click()
        expect(error_page.locator('#watch')).to_be_enabled();error_page.close()
        passed('catalog error disables playback and retry restores the same entry')
        storage_page=context.new_page();storage_page.on('pageerror',lambda e:errors.append(str(e)))
        storage_page.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw new DOMException('blocked','SecurityError')}})")
        storage_page.goto(args.base);expect(storage_page.locator('#finish')).to_be_enabled()
        storage_page.locator('#finish').click();expect(storage_page.locator('#verdict')).to_be_visible()
        storage_page.close()
        passed('storage restrictions do not block public replay or final audit')
        if args.local:
            tech=page.get_by_text('技术详情与运行边界',exact=True)
            if page.locator('.technical').first.evaluate('(d)=>!d.open'):tech.click()
            expect(page.locator('#run-model')).to_be_disabled()
            def start(cid):
                if page.locator('.technical').first.evaluate('(d)=>!d.open'):tech.click()
                page.select_option('#case-select',cid);page.locator('#run-program').click()
                expect(page.locator('.approval')).to_have_count(2)
                expect(page.locator('.result-summary').first).to_contain_text('尚未写入')
                expect(page.locator('.checks')).to_have_count(0)
            def confirm(policy):
                column=page.locator('[data-policy='+policy+']')
                column.get_by_role('button',name='确认此变更',exact=True).click()
                expect(page.locator('#run-program')).to_be_enabled(timeout=15000)
            def records():
                ids=page.evaluate('JSON.parse(localStorage.getItem("agent-bench-runs-v1"))')
                return [page.request.get(args.base.split('/agent-bench')[0]+'/api/runs/'+rid).json() for rid in ids]
            start('normal');tech.click();page.screenshot(path=str(out/'desktop-approval.png'),full_page=True)
            confirm('baseline');confirm('hardened')
            assert all(r['evaluation']['passed'] for r in records())
            passed('local normal flow: exact approval, SQLite writes and checks')
            start('timeout');confirm('baseline');confirm('hardened')
            expect(page.locator('[data-policy=baseline] .state')).to_have_text('结果未知')
            page.locator('[data-policy=baseline]').get_by_role('button',name='查询原操作并恢复').click()
            expect(page.locator('#run-program')).to_be_enabled()
            assert all(len(r['operations'])==1 and len(r['ticket']['notes'])==1 for r in records())
            passed('timeout recovery queries original operation and adds no duplicate note')
            start('duplicate');confirm('baseline');confirm('hardened')
            assert all(any(e['result'].get('deduplicated') for e in r['events']) for r in records())
            passed('duplicate transport delivery returns original receipt')
            start('conflict');confirm('baseline');confirm('hardened')
            expect(page.locator('[data-policy=hardened] .approval')).to_contain_text('v2')
            confirm('hardened');a,b=records();assert not a['ticket']['notes'] and len(b['ticket']['notes'])==1
            passed('stale approval is rejected and hardened flow asks again for v2')
            start('cancel')
            for policy in ('baseline','hardened'):
                page.locator('[data-policy='+policy+']').get_by_role('button',name='取消后续步骤').click();expect(page.locator('#run-program')).to_be_enabled()
            assert all(r['run']['state']=='cancelled' and r['ticket']['notes']==[] for r in records())
            passed('cancel before write leaves both databases unchanged')
            start('interrupted');confirm('baseline');confirm('hardened')
            assert all(r['run']['state']=='unknown' for r in records())
            page.reload();page.wait_for_load_state('networkidle');page.get_by_text('技术详情与运行边界',exact=True).click();page.locator('#restore').click()
            expect(page.locator('#run-program')).to_be_enabled()
            for policy in ('baseline','hardened'):
                page.locator('[data-policy='+policy+']').get_by_role('button',name='查询原操作并恢复').click();expect(page.locator('#run-program')).to_be_enabled()
            assert all(r['evaluation']['passed'] and len(r['operations'])==1 for r in records())
            passed('refresh resumes persistent run IDs and safely recovers interrupted commits')
            page.set_viewport_size({'width':390,'height':844});start('normal')
            tech.click();page.screenshot(path=str(out/'mobile-approval.png'),full_page=True);confirm('baseline');confirm('hardened')
            assert not page.evaluate('document.documentElement.scrollWidth>innerWidth')
            passed('mobile local approval flow completes both policies')
            page.set_viewport_size({'width':1440,'height':1000})
            tech.click()
            page.route('**/api/runs/*/step',lambda route:route.fulfill(status=503,content_type='application/json',body='{"message":"测试接口中断，请恢复原运行"}'))
            page.select_option('#case-select','normal');page.locator('#run-program').click();expect(page.locator('#error')).to_contain_text('测试接口中断')
            expect(page.locator('#source-label')).to_contain_text('本地程序测试');page.unroute('**/api/runs/*/step')
            page.locator('#restore').click();expect(page.locator('.approval')).to_have_count(2)
            passed('API failure preserves run and never silently converts to example mode')
        if args.home:
            home=context.new_page();home.goto(args.home);home.wait_for_load_state('networkidle')
            entry=home.locator('#project-agent-bench');expect(entry).to_be_visible();expect(entry.locator('a[href="/agent-bench/"]')).to_have_count(1)
            passed('portfolio entry preserved and routes to agent-bench')
        assert not errors,errors
        passed('no browser JavaScript errors')
        browser.close()
    (out/'browser-results.json').write_text(json.dumps({'base':args.base,'local':args.local,'checks':checks,'passed':len(checks),'errors':errors,'model_calls':0},ensure_ascii=False,indent=2)+'\n')
    print('Browser checks:',len(checks))

if __name__=='__main__':main()
